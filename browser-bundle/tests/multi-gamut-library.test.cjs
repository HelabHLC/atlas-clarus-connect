/* Run: node browser-bundle/tests/multi-gamut-library.test.cjs */
'use strict';
const assert=require('node:assert/strict');
const api=require('../src/multi-gamut-library.js');
const colors=Array.from({length:api.COUNT},(_,id)=>({id,ref:'REF_'+id,lab:[50,id%100,0]}));
const master={master_sha256:api.MASTER,entry_count:api.COUNT,colors};
const e=api.create(master);
e.registerLibrary('textile','TextileRGB');
e.registerLibrary('offset','Offset');
const sha='a'.repeat(64);
e.registerProfile({id:'fogra58',library_id:'textile',icc_sha256:sha,description:'Test ICC',method:'Lab RGB Lab 8-bit',intent:'relative'});
e.registerProfile({id:'pso',library_id:'offset',icc_sha256:'b'.repeat(64),description:'Test ICC',method:'Lab CMYK Lab',intent:'relative'});
assert.deepEqual(e.importResults('fogra58',[{atlas_row_id:1,reference:'REF_1',delta_e00:0.4},{atlas_row_id:2,delta_e00:0.9}]),{profile_id:'fogra58',imported:2,complete:false});
e.importResults('pso',[{atlas_row_id:2,delta_e00:0.2},{atlas_row_id:3,delta_e00:0.5}]);
assert.deepEqual(e.query(['fogra58','pso'],1,'intersection').ids,[2]);
assert.deepEqual(e.query(['fogra58','pso'],1,'union').ids,[1,2,3]);
assert.deepEqual(e.query(['fogra58','pso'],1,'difference').ids,[1]);
assert.equal(e.memberships(2,1).filter(x=>x.within_tolerance).length,2);
assert.equal(e.memberships(3,1).find(x=>x.profile_id==='fogra58').checked,false);
assert.equal(e.closest(1,['fogra58','pso'],1,3).candidates[0].atlas_row_id,2);
assert.equal(e.closest(1,['fogra58','pso'],1,3).ranking_method,'CIEDE2000_FULL_CANDIDATE_RANKING');
assert.ok(Math.abs(e.closest(1,['fogra58','pso'],1,3).candidates[0].delta_e00_to_target-1.36206672)<0.0001);
assert.throws(()=>e.importResults('fogra58',[{atlas_row_id:1,reference:'WRONG',delta_e00:0.2}]));
assert.deepEqual(e.query(['fogra58'],1).ids,[1,2]);
e.importResults('fogra58',[{atlas_row_id:3,delta_e00:0.1}]);
assert.deepEqual(e.query(['fogra58'],1).ids,[3]);
assert.throws(()=>e.registerProfile({id:'fogra58',library_id:'textile',icc_sha256:sha,description:'X',method:'X',intent:'X'}));
assert.throws(()=>api.create({...master,master_sha256:'wrong'}));
console.log('Multi-Gamut engine: tests passed');
