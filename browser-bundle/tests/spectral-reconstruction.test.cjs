'use strict';
const assert=require('node:assert/strict');
const {reconstruct,deltaE00}=require('../src/spectral-reconstruction.js');
const hash='a'.repeat(64),grid=[400,500,600];
const weights={illuminant:'D50',observer:'CIE1931_2',sha256:hash,wavelength_nm:grid,xyz_weights:[[.2,.1,.05],[.3,.5,.2],[.5,.4,.75]],white_xyz:[1,1,1]};
const n=(ref,v)=>({reference:ref,provenance:'MEASURED',source_sha256:hash,weight:1,wavelength_nm:grid,reflectance:[v,v,v]});
assert.ok(Math.abs(deltaE00([50,2,3],[50,2,3]))<1e-12);
assert.ok(Math.abs(deltaE00([50,2.6772,-79.7751],[50,0,-82.7485])-2.0425)<.0001);
const x=reconstruct({reference:'TEST',target_lab:[50,0,0],neighbours:[n('A',.2),n('B',.8)],weights});
assert.deepEqual(x.reflectance,[.5,.5,.5]);
assert.equal(x.validation_status,'PENDING_VALIDATION');
assert.equal(x.provenance,'SYNTHETIC_RECONSTRUCTED');
assert.equal(x.physical_validation,'NOT_PERFORMED');
const y=reconstruct({reference:'TEST',target_lab:x.roundtrip_lab,neighbours:[n('A',.2),n('B',.8)],weights,tolerance_de00:.1});
assert.equal(y.validation_status,'NUMERICAL_ROUNDTRIP_PASSED');
assert.equal(y.delta_e00,0);
assert.throws(()=>reconstruct({reference:'TEST',target_lab:[50,0,0],neighbours:[{...n('A',.2),provenance:'SYNTHETIC'},n('B',.8)],weights}),/provenance/);
assert.throws(()=>reconstruct({reference:'TEST',target_lab:[50,0,0],neighbours:[n('A',.2),n('B',.8)],weights:{...weights,illuminant:'D65'}}),/D50/);
console.log('Experimental spectral reconstruction: tests passed');
