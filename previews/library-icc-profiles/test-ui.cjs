 assert.equal(await page.locator('#kit-ba .ba-card').count(),3);
 if(shots)await page.screenshot({path:require('node:path').join(shots,'startup-icc.png'),fullPage:true});
 await select.selectOption('pso_uncoated_v3_fogra52');
 await page.getByRole('button',{name:'Für Druckvorbereitung übernehmen'}).click();
